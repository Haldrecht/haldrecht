export function catalogusLd(site: URL, taal: "nl" | "en") {
  const pad = taal === "nl" ? "/diensten/" : "/en/diensten/";
  let positie = 1;
  const diensten = CATALOGUS.flatMap((groep) =>
    groep.items.map((item) => ({
      "@type": "ListItem",
      position: positie++,
      item: {
        "@type": "Service",
        name: item.naam,
        serviceType: `${groep.nr} ${groep.titel}`,
        description: `${groep.fase}. [${item.rol}]`,
        additionalProperty: {
          "@type": "PropertyValue",
          name: "markering",
          value: item.rol,
        },
      },
    })),
  );
  const zoektermen = ZOEKTERMEN.flatMap((groep) =>
    groep.termen.map((naam) => ({
      "@type": "ListItem",
      position: positie++,
      item: {
        "@type": "Service",
        name: naam,
        serviceType: groep.titel,
        additionalProperty: {
          "@type": "PropertyValue",
          name: "soort",
          value: "zoekterm",
        },
      },
    })),
  );
  return {
    "@context": "https://schema.org",
    "@type": "OfferCatalog",
    name: taal === "nl" ? "Diensten" : "Services",
    url: new URL(pad, site).href,
    itemListElement: [...diensten, ...zoektermen],
  };
}
